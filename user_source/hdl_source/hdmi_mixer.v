    function [23:0] F_bcd_add3;
        input [23:0] I_bcd;
        integer digit;
        reg [23:0] value;
        begin
            value = I_bcd;
            for(digit = 0; digit < 6; digit = digit + 1) begin
                if(value[digit*4 +: 4] >= 4'd5)
                    value[digit*4 +: 4] = value[digit*4 +: 4] + 4'd3;
            end
            F_bcd_add3 = value;
        end
    endfunction

